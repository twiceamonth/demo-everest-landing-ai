/**
 * Получить тарифы/абонементы из WordPress REST API или мока
 */
export async function fetchPricing(): Promise<PricingResponse> {
  if (USE_WORDPRESS_API) {
    const response = await fetch('https://everest.tomsk.ru/wp-json/everest/v1/pricing', {
      cache: 'no-store',
    });
    
    if (!response.ok) {
      throw new Error('Не удалось загрузить цены');
    }
    
    return response.json();
  }
  
  // Имитируем задержку сети
  await new Promise(resolve => setTimeout(resolve, 300));
  return MOCK_PRICING;
}
